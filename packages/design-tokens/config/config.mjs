/**
 * Style Dictionary config.
 * Registers custom transforms, formats, and actions, then exports build configs
 * that produce CSS, TS, JSON, iOS, and Android outputs from DTCG token sources.
 *
 * Layers: primitives → light (default) → dark (override)
 * Output:  dist/{css,ts,json,ios,android}/
 */

